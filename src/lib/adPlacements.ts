/**
 * Регулы размещения рекламных блоков РСЯ.
 *
 * Блоки РСЯ уже смонтированы на страницах, но включаются только когда в
 * окружении Vercel задан настоящий ID блока (NEXT_PUBLIC_YANDEX_*_AD_ID).
 * Пока ID нет, компонент рисует null — это правильно: пустой div ломает
 * вёрстку, а «рыбный» ID даёт 400 от Яндекса в консоли на каждой странице.
 *
 * Здесь собраны два правила, которые нельзя выразить в компоненте:
 *
 * 1. **Не показывать рекламу на странице купона.** Человек пришёл скопировать
 *    код и уйти в магазин. Баннер рядом с кодом уводит его с конверсии, за
 *    которую мы получаем комиссию. Доход от CPA на таких страницах выше, чем
 *    от показа, поэтому реклама там работает против нас.
 *
 * 2. **Не показывать рекламу у офферов конкурентов.** Если на странице есть
 *    блок с предложением другой CPA-сети, показывать рядом объявление
 *    чужого магазина — значит отдавать клик бесплатно.
 */

/** Страницы, где рекламный блок не ставится никогда. */
const AD_FREE_PATHS = [
  /^\/store\/[^/]+$/, // карточка купонов магазина — только товар и кнопка
];

export function isAdAllowedOnPath(pathname: string): boolean {
  return !AD_FREE_PATHS.some((re) => re.test(pathname));
}

/**
 * Черновик: мягкая зона прогрева.
 *
 * Первые полгода жизни домена рекламные блоки на страницах каталога дают
 * почти ноль (нет трафика, нет показов) и добавляют вес в LCP. Статьи — другое
 * дело: там человек читает и блок между абзацами его не отвлекает от покупки.
 */
export const ADS_EARLY_PHASE_PATHS = [/^\/sovety/, /^\/category\//];
