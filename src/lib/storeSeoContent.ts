/**
 * Генератор уникального SEO-текста для страниц /store/[slug].
 *
 * Зачем: страницы магазинов шаблонные — весь текст подставлял только имя
 * магазина, и при отсутствии `about` у многих магазинов копия была почти
 * идентичной (мягкий дубль, который Google демотит). Здесь текст собирается из
 * реальных фактов конкретного магазина: категория, число активных купонов,
 * коды и их названия, максимальный дисконт, первый-ли заказ, условия, количество
 * блогеров. Плюс категорийные «углы» разбиты на банки и выбираются по хэшу слоуга,
 * чтобы два магазина одной категории не звучали одинаково.
 */

export interface StoreArticleInput {
  name: string;
  category: string;
  categorySlug: string;
  site?: string | null;
  about?: string | null;
  conditions?: string | null;
  /** Активные купоны: только коды/названия. */
  coupons: { code: string; bonusName: string | null }[];
  couponCount: number;
  maxDiscount: string;
  isFirstOrder: boolean;
  activeBloggers: number;
  monthYear: string;
  monthRu: string;
  todayRu: string;
}

type Fill = Record<string, string | number>;

function fill(tpl: string, f: Fill): string {
  return tpl.replace(/\{(\w+)\}/g, (_m, k) => (k in f ? String(f[k]) : `{${k}}`));
}

