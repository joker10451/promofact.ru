const CATEGORY_FALLBACK = [
  "Промокод {name} помогает купить нужное дешевле, если вставить код в корзину до оплаты.",
  "Купон {name} снижает сумму чека при соблюдении условий акции — всегда читайте их перед переходом в магазин.",
];

function hashForPick(key: string): number {
  let h = 0;
  for (let i = 0; i < key.length; i += 1) {
    h = (h * 31 + key.charCodeAt(i)) >>> 0;
  }
  return h;
}

function pickAngle(categorySlug: string, slug: string): string {
  const bank = CATEGORY_ANGLES[categorySlug] ?? CATEGORY_FALLBACK;
  return bank[hashForPick(slug) % bank.length];
}

/** Число активных купонов и названия кодов в тексте. */
function codesSentence(input: StoreArticleInput): string {
  const active = input.coupons.filter((c) => c.code);
  if (active.length === 0) {
    return `Сейчас активных промокодов ${input.name} нет — новые коды появляются на этой странице по мере запуска партнёрских акций. Заглядывайте позже или подпишитесь, чтобы не пропустить свежую скидку.`;
  }
  const tops = active
    .slice(0, 3)
    .map((c) => `«${c.code}»${c.bonusName ? " — " + c.bonusName : ""}`)
    .join(", ");
  const list = active
    .map((c) => c.code)
    .join(", ");
  const countWord =
    active.length === 1
      ? "промокод"
      : active.length >= 2 && active.length <= 4
        ? "промокода"
        : "промокодов";
  return `Сейчас у ${input.name} действует ${active.length} ${countWord}${tops ? `: ${tops}` : ""}. Все коды проверены и приводятся в карточке купона с условиями применения.`;
}

function buildParagraphs(input: StoreArticleInput, slug: string): string[] {
  const monthYear = input.monthYear;
  const monthRu = input.monthRu;
  const f: Fill = {
    name: input.name,
    category: input.category,
    max: input.maxDiscount,
    monthYear,
    monthRu,
    todayRu: input.todayRu,
    bloggers: input.activeBloggers,
  };

  const countWord =
    input.couponCount === 1
      ? "рабочий промокод"
      : input.couponCount >= 2 && input.couponCount <= 4
        ? "рабочих промокода"
        : "рабочих промокодов";

  // 1. Лид — уникальный за счёт числа скидок, месяца и максимальной выгоды.
  let lead: string;
  if (input.couponCount > 0) {
    lead = `На странице «Промокоды ${input.name}» собраны актуальные и проверенные купоны на ${monthRu}. Скидка на ${input.category} сегодня достигает ${input.maxDiscount}, всего действует ${input.couponCount} ${countWord}. Коды проверены командой ПромоФакт, срок действия указан в карточке каждого купона.`;
  } else {
    lead = `Страница «Промокоды ${input.name}» по категории «${input.category}». Сейчас действующих купонов нет, но подборку обновляем по мере старта партнёрских акций — новые коды появляются в день запуска.`;
  }

  // 2. Категорийный угол (выбирается по хэшу слоуга — два магазина одной категории различаются).
  const angle = fill(pickAngle(input.categorySlug, slug), f);

  // 3. Коды / бонусы — реальные данные конкретного магазина.
  const codes = codesSentence(input);

  // 4. Первый заказ / условия.
  let order: string;
  if (input.isFirstOrder && input.couponCount > 0) {
    order = `Обратите внимание: часть промокодов ${input.name} действует только на первый заказ — такие коды помечены в карточке. Другие условия (минимальная сумма, категория товаров) описаны под каждым купоном.`;
  } else {
    order = `Большинство промокодов ${input.name} подходят как новым, так и постоянным клиентам. Если код не сработал, проверьте минимальную сумму заказа и ограничения по категории товаров — они указаны в условиях акции.`;
  }

  // 5. Доверие (ссылка на сайт магазина ставится отдельным якорем в странице).
  const bloggers = input.activeBloggers
    ? ` Подборку рекомендуют ${input.activeBloggers} блогеров.`
    : "";
  const trust = `Все коды мы проверяем вручную раз в 1–2 дня: истёкшие убираем сразу, а рабочие оставляем.${bloggers} ПромоФакт зарабатывает на партнёрских комиссиях, поэтому для вас купоны полностью бесплатны.`;

  return [lead, angle, codes, order, trust];
}

export function buildStoreArticle(input: StoreArticleInput, slug: string): string[] {
  return buildParagraphs(input, slug);
}

export function buildStoreDescription(input: StoreArticleInput): string {
  const codes = input.coupons
    .slice(0, 3)
    .map((c) => c.code)
    .join(", ");
  const base = `Проверенные промокоды ${input.name} на ${input.monthRu}: ${input.couponCount} ${input.couponCount === 1 ? "код" : input.couponCount >= 2 && input.couponCount <= 4 ? "кода" : "кодов"} со скидкой ${input.maxDiscount}`;
  const codesPart = codes ? ` [${codes}]` : "";
  return `${base}${codesPart}. Копируй и экономь на заказе!`;
}
